// Writes src/admin-api.gen.ts: the Admin API's types (paths, request bodies, responses), straight from the router,
// so apps call `shop.admin.api` with types that can't drift from the server. Run `pnpm generate` after changing an
// Admin API route; the file is committed so apps (and anyone using @shopnex/app) need nothing but the package.
import { writeFile } from 'node:fs/promises'
import { OpenAPIGenerator } from '@orpc/openapi'
import { ZodToJsonSchemaConverter } from '@orpc/zod/zod4'
import { router } from '@shopnex/api/router'
import openapiTS, { astToString } from 'openapi-typescript'

const ADMIN = '/admin'

const spec = await new OpenAPIGenerator({ schemaConverters: [new ZodToJsonSchemaConverter()] }).generate(router, {
  info: { title: 'ShopNex Admin API', version: '1.0.0' },
})

// The client's base URL is {instance}/api/v1/admin, so its paths start after /admin
const paths = Object.fromEntries(
  Object.entries(spec.paths ?? {})
    .filter(([path]) => path.startsWith(`${ADMIN}/`))
    .map(([path, item]) => [path.slice(ADMIN.length), item]),
)

const ast = await openapiTS({ ...spec, paths } as Parameters<typeof openapiTS>[0])
const header = '// Generated by `pnpm --filter @shopnex/app generate` from the Admin API router. Do not edit.\n\n'
await writeFile(new URL('../src/admin-api.gen.ts', import.meta.url), header + astToString(ast))
console.log(`Wrote src/admin-api.gen.ts (${Object.keys(paths).length} paths)`)
