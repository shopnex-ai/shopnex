// Where uploaded bytes live: `local` (the server's disk, the default) or an S3-compatible bucket
// (./s3, configured per shop in ./backends). Each file row records the backend that holds it.
import { createReadStream } from 'node:fs'
import { mkdir, rm, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { Readable } from 'node:stream'

export interface StorageProvider {
  /** Stored on file rows: 'local', or the storage_backends id */
  readonly name: string
  put(key: string, body: Uint8Array<ArrayBuffer>, contentType: string): Promise<void>
  /** No-op when the object is already gone */
  delete(key: string): Promise<void>
  /** Absolute URL storefronts and the admin load the file from */
  url(key: string): string
}

// Keys are generated by the files service; anything else (e.g. `..`) never reaches the disk
export const KEY_PATTERN = /^[A-Za-z0-9_-]+\/[A-Za-z0-9-]+\.[a-z0-9]+$/

// Same origin the hosted checkout links use
const publicOrigin = () =>
  (process.env.APP_URL ?? process.env.BETTER_AUTH_URL ?? 'http://localhost:3000').replace(/\/$/, '')

/** Directory for local files; mount a volume here when self-hosting */
const localRoot = () => path.resolve(process.env.FILES_DIR ?? '.data/files')

function localPath(key: string) {
  if (!KEY_PATTERN.test(key)) throw new Error(`Invalid file key: ${key}`)
  return path.join(localRoot(), key)
}

export const localDisk: StorageProvider = {
  name: 'local',
  async put(key, body) {
    const file = localPath(key)
    await mkdir(path.dirname(file), { recursive: true })
    await writeFile(file, body, { flag: 'wx' })
  },
  async delete(key) {
    await rm(localPath(key), { force: true })
  },
  // Served by the API (GET /api/files/{key})
  url: (key) => `${publicOrigin()}/api/files/${key}`,
}

/** For the API's file route: null when there's no such local file */
export async function readLocalFile(key: string) {
  if (!KEY_PATTERN.test(key)) return null
  const file = localPath(key)
  const info = await stat(file).catch(() => null)
  if (!info?.isFile()) return null
  return { size: info.size, body: Readable.toWeb(createReadStream(file)) as ReadableStream<Uint8Array> }
}
